// Build the Aidoku (iOS) source list: one .aix package per comic / novel source.
//   .build/aidoku/<id>.js         engine bundle written by build-all.mjs (vBook scripts + runtime + hosts/aidoku.tail.js)
//   .build/aidoku-ws/             generated Cargo workspace (one tiny crate per source + aidoku/bridge)
//   repo/aidoku/index.min.json    source list to add in Aidoku (Settings > Source Lists)
//   repo/aidoku/sources/*.aix     packages: Payload/{main.wasm, source.json, settings.json, icon.png}
//   repo/aidoku/icons/*.png
// Needs Rust + the wasm32-unknown-unknown target. Without a downloadable target (offline machines) set
// AIDOKU_BUILD_STD=1 and a rust-src copy: the core/alloc libraries are then compiled from source.
// Usage: node tools/build/aidoku-build.mjs [--only id1,id2] [--jobs N] [--no-build]
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { makeZip } from './zip.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const args = process.argv.slice(2);
const opt = k => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : null; };
const ONLY = opt('--only') ? new Set(opt('--only').split(',')) : null;
const AK = path.join(ROOT, '.build/aidoku');
const WS = path.join(ROOT, '.build/aidoku-ws');
const OUT = path.join(ROOT, 'repo/aidoku');
const VERSION = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version;
// Bump when the bridge or the Aidoku adapter changes: package version = BRIDGE_REV * 100 + source version.
const BRIDGE_REV = 1;
const LANG = { vi: 'vi', 'zh-CN': 'zh', zh: 'zh', en: 'en', ja: 'ja', global: 'multi', all: 'multi' };
const crate = id => 'kiri-' + id.toLowerCase().replace(/[^a-z0-9]+/g, '-');
export const aidokuId = s => `${LANG[s.lang] || 'multi'}.kiritokmn.${s.id.toLowerCase().replace(/[^a-z0-9]+/g, '')}`;

const all = JSON.parse(fs.readFileSync(path.join(AK, 'sources.json'), 'utf8'));
const list = all.filter(s => !ONLY || ONLY.has(s.id));

function sourceJson(s) {
  const info = {
    id: aidokuId(s), name: s.name, version: BRIDGE_REV * 100 + (s.version | 0), url: s.source,
    urls: [...new Set([s.source, ...(s.domains || [])])].slice(0, 10),
    contentRating: s.nsfw ? 2 : 0, languages: [LANG[s.lang] || 'multi'],
    // text pages (novels) need Aidoku 0.8.3+; the JS context API is older than that
    minAppVersion: '0.8.3',
  };
  return { info, listings: [{ id: 'tab0', name: s.type === 'novel' ? 'Truyện' : 'Phổ biến' }] };
}
function settingsJson(s) {
  const doms = [...new Set([s.source, ...(s.domains || [])])];
  const item = doms.length > 1
    ? { type: 'select', key: 'DOMAIN', title: 'Tên miền / Domain', values: doms, default: doms[0], refreshes: ['content', 'listings'] }
    : { type: 'text', key: 'DOMAIN', title: 'Tên miền / Domain', placeholder: s.source, default: s.source, keyboardType: 3, autocorrectionDisabled: true, autocapitalizationType: 0, refreshes: ['content', 'listings'] };
  return [{ type: 'group', title: 'Kiritokmn Extension Repo ' + VERSION, footer: 'Đổi tên miền khi trang chuyển địa chỉ (VD: https://example.com).', items: [item] }];
}
function libRs(s) {
  const webtoon = s.type === 'comic' && /^(vi|zh)/.test(s.lang);
  return `// Generated by tools/build/aidoku-build.mjs — do not edit. Source: sources/${s.id}/
#![no_std]
use aidoku::{
	BaseUrlProvider, Chapter, DynamicListings, FilterValue, ImageRequestProvider, Listing, ListingProvider, Manga,
	MangaPageResult, Page, PageContext, Result, Source,
	alloc::{String, Vec},
	imports::net::Request,
	prelude::*,
};
use kiri_bridge::{Bridge, Info};

static JS: &str = include_str!("../engine.js");

struct Kiri(Bridge);

impl Source for Kiri {
	fn new() -> Self {
		Kiri(Bridge::new(JS, Info { nsfw: ${!!s.nsfw}, comic: ${s.type === 'comic'}, webtoon: ${webtoon}, default_base: ${JSON.stringify(s.source.replace(/\/+$/, ''))} }))
	}
	fn get_search_manga_list(&self, query: Option<String>, page: i32, _filters: Vec<FilterValue>) -> Result<MangaPageResult> {
		self.0.search(query, page)
	}
	fn get_manga_update(&self, manga: Manga, needs_details: bool, needs_chapters: bool) -> Result<Manga> {
		self.0.manga(manga, needs_details, needs_chapters)
	}
	fn get_page_list(&self, _manga: Manga, chapter: Chapter) -> Result<Vec<Page>> {
		self.0.pages(chapter)
	}
}
impl ListingProvider for Kiri {
	fn get_manga_list(&self, listing: Listing, page: i32) -> Result<MangaPageResult> {
		self.0.listing(listing, page)
	}
}
impl DynamicListings for Kiri {
	fn get_dynamic_listings(&self) -> Result<Vec<Listing>> {
		self.0.listings()
	}
}
impl ImageRequestProvider for Kiri {
	fn get_image_request(&self, url: String, context: Option<PageContext>) -> Result<Request> {
		self.0.image_request(url, context)
	}
}
impl BaseUrlProvider for Kiri {
	fn get_base_url(&self) -> Result<String> {
		self.0.base_url()
	}
}

register_source!(Kiri, ListingProvider, DynamicListings, ImageRequestProvider, BaseUrlProvider);

#[cfg(test)]
mod tests {
	use super::*;
	use aidoku_test::aidoku_test;

	// Full chain like the app: listing -> details + chapters -> pages/text (run with aidoku-test-runner)
	#[aidoku_test]
	fn chain() {
		let src = Kiri::new();
		let tabs = src.get_dynamic_listings().expect("listings");
		println!("listings: {}", tabs.len());
		let list = src.get_manga_list(tabs[0].clone(), 1).expect("listing");
		println!("entries: {} next={}", list.entries.len(), list.has_next_page);
		assert!(!list.entries.is_empty(), "empty listing");
		let m = src.get_manga_update(list.entries[0].clone(), true, true).expect("details");
		let chapters = m.chapters.clone().unwrap_or_default();
		println!("title: {} chapters: {}", m.title, chapters.len());
		let ch = chapters.iter().rev().find(|c| !c.locked).cloned().expect("no chapter");
		let pages = src.get_page_list(m, ch).expect("pages");
		println!("pages: {}", pages.len());
		assert!(!pages.is_empty(), "no pages");
	}
}
`;
}

// ---- generate the workspace
fs.mkdirSync(path.join(WS, 's'), { recursive: true });
const AIDOKU_DEP = 'aidoku = { git = "https://github.com/Aidoku/aidoku-rs", rev = "ae6485e", features = ["json"] }';
const keep = new Set(list.map(s => crate(s.id)));
if (!ONLY) for (const d of fs.readdirSync(path.join(WS, 's'))) if (!keep.has(d)) fs.rmSync(path.join(WS, 's', d), { recursive: true, force: true });
fs.writeFileSync(path.join(WS, 'Cargo.toml'), `# Generated by tools/build/aidoku-build.mjs
[workspace]
members = ["s/*"]
resolver = "3"

[workspace.dependencies]
${AIDOKU_DEP}
aidoku-test = { git = "https://github.com/Aidoku/aidoku-rs", rev = "ae6485e" }
kiri-bridge = { path = "../../aidoku/bridge" }

[profile.dev]
panic = "abort"

[profile.release]
panic = "abort"
opt-level = "s"
strip = true
lto = true
codegen-units = 1
`);
for (const s of list) {
  const d = path.join(WS, 's', crate(s.id));
  fs.mkdirSync(path.join(d, 'src'), { recursive: true }); fs.mkdirSync(path.join(d, 'res'), { recursive: true });
  const w = (f, c) => { const p = path.join(d, f); if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== c) fs.writeFileSync(p, c); }; // keep mtimes -> incremental builds
  w('Cargo.toml', `[package]\nname = "${crate(s.id)}"\nversion = "0.1.${s.version | 0}"\nedition = "2024"\npublish = false\n\n[lib]\ncrate-type = ["cdylib"]\n\n[dependencies]\naidoku = { workspace = true }\nkiri-bridge = { workspace = true }\n\n[dev-dependencies]\naidoku = { workspace = true, features = ["test"] }\naidoku-test = { workspace = true }\n`);
  w('src/lib.rs', libRs(s));
  w('engine.js', fs.readFileSync(path.join(AK, s.id + '.js'), 'utf8'));
  w('res/source.json', JSON.stringify(sourceJson(s), null, '\t'));
  w('res/settings.json', JSON.stringify(settingsJson(s), null, '\t'));
}

// ---- compile
const TARGET = 'wasm32-unknown-unknown';
const env = { ...process.env };
const cargoArgs = ['build', '--release', '--target', TARGET];
if (process.env.AIDOKU_BUILD_STD) { env.RUSTC_BOOTSTRAP = '1'; cargoArgs.push('-Zbuild-std=core,alloc'); }
if (opt('--jobs')) cargoArgs.push('-j', opt('--jobs'));
if (ONLY) for (const s of list) cargoArgs.push('-p', crate(s.id));
if (!args.includes('--no-build')) {
  const t0 = Date.now();
  execFileSync('cargo', cargoArgs, { cwd: WS, env, stdio: 'inherit' });
  console.log(`cargo: ${((Date.now() - t0) / 1000).toFixed(0)}s`);
}

// ---- package (.aix = zip with Payload/) + source list
fs.mkdirSync(path.join(OUT, 'sources'), { recursive: true }); fs.mkdirSync(path.join(OUT, 'icons'), { recursive: true });
if (!ONLY) for (const f of [...fs.readdirSync(path.join(OUT, 'sources')).map(x => 'sources/' + x), ...fs.readdirSync(path.join(OUT, 'icons')).map(x => 'icons/' + x)]) fs.rmSync(path.join(OUT, f));
const indexFile = path.join(OUT, 'index.min.json');
const prev = fs.existsSync(indexFile) ? JSON.parse(fs.readFileSync(indexFile, 'utf8')).sources || [] : [];
const items = ONLY ? prev.filter(x => !list.some(s => aidokuId(s) === x.id)) : [];
const report = [];
for (const s of list) {
  const wasm = path.join(WS, 'target', TARGET, 'release', crate(s.id).replace(/-/g, '_') + '.wasm');
  if (!fs.existsSync(wasm)) { report.push({ id: s.id, ok: false, error: 'wasm missing' }); continue; }
  const sj = sourceJson(s), aid = sj.info.id, ver = sj.info.version;
  const icon = fs.readFileSync(path.join(ROOT, 'aidoku/icons', s.id + '.png'));
  const files = [
    { name: 'Payload/main.wasm', data: fs.readFileSync(wasm) },
    { name: 'Payload/source.json', data: JSON.stringify(sj, null, '\t') },
    { name: 'Payload/settings.json', data: JSON.stringify(settingsJson(s), null, '\t') },
    { name: 'Payload/icon.png', data: icon },
  ];
  const aix = makeZip(files);
  fs.writeFileSync(path.join(OUT, 'sources', `${aid}-v${ver}.aix`), aix);
  fs.writeFileSync(path.join(OUT, 'icons', `${aid}-v${ver}.png`), icon);
  items.push({ id: aid, name: s.name, version: ver, iconURL: `icons/${aid}-v${ver}.png`, downloadURL: `sources/${aid}-v${ver}.aix`, languages: sj.info.languages, contentRating: sj.info.contentRating, baseURL: s.source, minAppVersion: sj.info.minAppVersion, altNames: [s.type === 'novel' ? 'Novel' : 'Comic'] });
  report.push({ id: s.id, ok: true, aid, wasmKB: Math.round(fs.statSync(wasm).size / 1024), aixKB: Math.round(aix.length / 1024) });
}
items.sort((a, b) => a.id.localeCompare(b.id));
const index = { name: 'Kiritokmn Extension Repo', sources: items };
fs.writeFileSync(indexFile, JSON.stringify(index));
fs.writeFileSync(path.join(OUT, 'index.json'), JSON.stringify(index, null, 1));
fs.writeFileSync(path.join(ROOT, '.build/aidoku-report.json'), JSON.stringify(report, null, 1));
const ok = report.filter(r => r.ok);
console.log(`aidoku: ${ok.length}/${report.length} packages, ${(ok.reduce((a, r) => a + r.aixKB, 0) / 1024).toFixed(1)} MB`);
